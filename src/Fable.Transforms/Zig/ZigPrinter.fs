module Fable.Transforms.Zig.ZigPrinter

open Fable.Transforms
open Fable.Transforms.Zig.Compiler

let isEmpty (file: ZigFile) : bool =
    System.String.IsNullOrWhiteSpace file.Body

let run (writer: Printer.Writer) (file: ZigFile) : Async<unit> =
    async {
        let sb = System.Text.StringBuilder()

        sb
            .AppendLine("// Generated by Fable (Zig target)")
            .AppendLine("const std = @import(\"std\");")
            // (this file, for the runtime to find its functions by name: `fable_rt.Hook`)
            .AppendLine("const @\"$file\" = @This();")
        |> ignore

        match file.Runtime with
        | Some path ->
            sb.AppendLine($"const fable_rt = @import(\"%s{writer.MakeImportPath path}\");")
            |> ignore
        | None -> ()

        for (alias, path) in file.Imports do
            sb.AppendLine($"const %s{alias} = @import(\"%s{writer.MakeImportPath path}\");")
            |> ignore

        sb.AppendLine().Append(file.Body) |> ignore
        do! writer.Write(sb.ToString())
    }
