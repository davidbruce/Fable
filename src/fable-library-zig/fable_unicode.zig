//! Case mapping for UTF-16 code units, as .NET's `Char.ToUpperInvariant` and
//! `Char.ToLowerInvariant` give it. The tables were written out from .NET 10 itself: every
//! code unit that maps to another one, as runs of units `stride` apart that all move by
//! `delta`. The runs are in order and do not overlap.

pub const CaseRun = struct { lo: u16, hi: u16, stride: u8, delta: i32 };

fn map(table: []const CaseRun, c: u16) u16 {
    var lo: usize = 0;
    var hi: usize = table.len;
    while (lo < hi) {
        const mid = (lo + hi) / 2;
        if (table[mid].hi < c) lo = mid + 1 else hi = mid;
    }
    if (lo == table.len) return c;
    const run = table[lo];
    if (c < run.lo or (c - run.lo) % run.stride != 0) return c;
    return @intCast(@as(i32, c) + run.delta);
}

pub fn toUpper(c: u16) u16 {
    if (c < 0x80) return if (c >= 'a' and c <= 'z') c - 32 else c;
    return map(&to_upper, c);
}

pub fn toLower(c: u16) u16 {
    if (c < 0x80) return if (c >= 'A' and c <= 'Z') c + 32 else c;
    return map(&to_lower, c);
}

/// `Char.IsWhiteSpace`
pub fn isWhiteSpace(c: u16) bool {
    return switch (c) {
        0x09...0x0D, 0x20, 0x85, 0xA0, 0x1680, 0x2000...0x200A, 0x2028, 0x2029, 0x202F, 0x205F, 0x3000 => true,
        else => false,
    };
}

